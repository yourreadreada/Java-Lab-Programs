public class ArrayProg
{
    public static void main(String args[])
    {
        int[] num={10,20,30,40,50};
        System.out.println("Length = "+num.length);
        System.out.println("Array: ");
        for(int i=0; i<(num.length); i++)
        {
            System.out.print(num[i]);
        }
    }
}